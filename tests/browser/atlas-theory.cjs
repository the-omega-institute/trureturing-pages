const { chromium } = require("playwright");
const assert = require("node:assert/strict");
const fs = require("node:fs");
const path = require("node:path");
const base = process.env.ATLAS_URL || "http://127.0.0.1:8765/atlas.html";
const output = process.env.ATLAS_OUTPUT || "artifacts/atlas-preview/theory";
fs.mkdirSync(output, { recursive: true });

(async () => {
  const browser = await chromium.launch({ channel: "chrome", headless: true });
  try {
    const page = await browser.newPage({ reducedMotion: "reduce", viewport: { width: 1512, height: 982 } });
    const errors = [];
    page.on("pageerror", e => errors.push(e.message));
    await page.goto(base + "?lang=en");
    await page.waitForFunction(() => window.atlasDiagnostics);
    await page.waitForTimeout(800);
    const initial = await page.evaluate(() => window.atlasDiagnostics());
    assert.equal(initial.mode, "theory");
    assert.equal(initial.theory.routes.length, 4);
    assert.deepEqual(initial.theory.unavailable, []);
    assert.equal(initial.nodes, initial.theory.nodes);
    assert.ok(initial.nodes < 100);
    assert.equal(await page.locator(".family-label:visible").count(), 0);
    await page.screenshot({ path: path.join(output, "theory-desktop.png") });
    await page.locator(".theory-route").first().click();
    assert.equal(await page.locator(".theory-steps li").count(), initial.theory.routes[0].ids.length);
    assert.equal(await page.evaluate(() => window.atlasDiagnostics().theory.route), "readouts");
    assert.ok(page.url().includes("route=readouts"));
    await page.screenshot({ path: path.join(output, "theory-route.png") });
    await page.locator(".theory-steps .concept-row").first().click();
    assert.equal(await page.evaluate(() => window.atlasDiagnostics().selected), initial.theory.routes[0].ids[0]);
    assert.ok(await page.locator(".article-copy").innerText());
    await page.locator(".article-audit summary").click();
    const sourceLink = await page.getByRole("link", { name: "Lean source at this release", exact: true }).getAttribute("href");
    assert.match(sourceLink, /github\.com\/the-omega-institute\/trureturing\/blob\/[a-f0-9]{40}\/.*\.lean$/);
    await page.getByRole("button", { name: "Previous view", exact: true }).click();
    assert.equal(await page.evaluate(() => window.atlasDiagnostics().selected), null);
    assert.equal(await page.evaluate(() => window.atlasDiagnostics().theory.route), "readouts");
    await page.getByRole("button", { name: "All theory routes", exact: true }).click();
    assert.equal(await page.locator(".theory-route").count(), 4);
    await page.getByRole("button", { name: "Dependencies", exact: true }).click();
    const full = await page.evaluate(() => window.atlasDiagnostics());
    assert.ok(full.nodes > initial.nodes);
    await page.getByRole("button", { name: "Return to all concepts", exact: true }).click();
    assert.equal(await page.evaluate(() => window.atlasDiagnostics().mode), "dependency");
    await page.getByRole("button", { name: "Theory", exact: true }).click();
    await page.getByLabel("Find a concept", { exact: true }).fill("Mellin Reconstruction");
    await page.locator("#search-results button").first().click();
    assert.ok((await page.evaluate(() => window.atlasDiagnostics().selected)).includes("CompletedZetaMellinReconstruction"));
    await page.getByRole("button", { name: "Return to all concepts", exact: true }).click();
    assert.equal(await page.evaluate(() => window.atlasDiagnostics().mode), "theory");
    assert.equal(await page.locator(".theory-route").count(), 4);

    const zh = await browser.newPage({ reducedMotion: "reduce", viewport: { width: 1512, height: 982 } });
    zh.on("pageerror", e => errors.push(e.message));
    await zh.goto(base + "?lang=zh-CN#route=measurement");
    await zh.waitForFunction(() => window.atlasDiagnostics);
    await zh.getByRole("heading", { name: "从记录到测量", exact: true }).waitFor();
    assert.equal(await zh.locator(".theory-steps li").count(), 5);
    await zh.screenshot({ path: path.join(output, "theory-chinese.png") });

    const mobile = await browser.newPage({ reducedMotion: "reduce", viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
    mobile.on("pageerror", e => errors.push(e.message));
    await mobile.goto(base + "?lang=en");
    await mobile.waitForFunction(() => window.atlasDiagnostics);
    assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await mobile.screenshot({ path: path.join(output, "theory-mobile.png"), fullPage: true });
    await mobile.locator(".theory-route").first().click();
    await mobile.locator(".theory-steps .concept-row").first().click();
    assert.ok(await mobile.locator("#wiki").evaluate(node => node.classList.contains("has-selection")));
    await mobile.getByRole("button", { name: "Previous view", exact: true }).click();
    assert.equal(await mobile.evaluate(() => window.atlasDiagnostics().theory.route), "readouts");
    await mobile.screenshot({ path: path.join(output, "theory-mobile-route.png"), fullPage: true });
    assert.deepEqual(errors, []);
    fs.writeFileSync(path.join(output, "receipt.json"), JSON.stringify({ nodes: initial.nodes, edges: initial.edges, fullNodes: full.nodes, routes: initial.theory.routes, errors }, null, 2));
    console.log(JSON.stringify({ nodes: initial.nodes, edges: initial.edges, fullNodes: full.nodes, routes: initial.theory.routes.length, errors }));
  } finally { await browser.close(); }
})().catch(e => { console.error(e); process.exit(1); });
